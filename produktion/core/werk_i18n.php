function werk_sprachen(): array { return ['de' => 'DE', 'en' => 'EN', 'uk' => 'УКР']; }

function werk_lang(): string {
    $l = (string)($_SESSION['werk_lang'] ?? ($_COOKIE['werk_lang'] ?? 'de'));
    return isset(werk_sprachen()[$l]) ? $l : 'de';
}

function werk_lang_setzen(string $l): void {
    if (!isset(werk_sprachen()[$l])) return;
    $_SESSION['werk_lang'] = $l;
    setcookie('werk_lang', $l, time() + 31536000, '/produktion/');
}

// Umschalter (drei Pillen) – als GET-Links auf ?setlang=.
function werk_lang_switcher(string $lang, int $id = 0): string {
    $base = '?p=werk' . ($id > 0 ? '&id=' . $id : '');
    $out  = '<div class="langsw">';
    foreach (werk_sprachen() as $code => $lbl)
        $out .= '<a class="langbtn' . ($code === $lang ? ' on' : '') . '" href="' . h($base . '&setlang=' . $code) . '">' . h($lbl) . '</a>';
    return $out . '</div>';
}

